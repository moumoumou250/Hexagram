CREATE VIEW hexagram_board AS
SELECT h.name, h.palace, h.palace_stage, l.*,
       CASE l.position WHEN h.shi_line THEN '世' WHEN h.ying_line THEN '应' ELSE '' END AS shi_ying,
       f.stem AS hidden_stem, f.branch AS hidden_branch, f.element AS hidden_element, f.relative AS hidden_relative
FROM hexagrams h JOIN hexagram_lines l ON h.hexagram_id=l.hexagram_id
LEFT JOIN hidden_spirits f ON f.hexagram_id=l.hexagram_id AND f.position=l.position;
COMMIT;
